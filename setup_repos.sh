#!/bin/bash

# Import repos defined in dependencies.repos
echo -e "\033[1;34m#####--- Cloning repositories \e[0m"
vcs import src < dependencies.repos

# Change remote push origin to https for tod_repos
echo -e "\n\e[32m#####--- Setting up tod_repos \e[0m"
SRC_DIR="$( cd -- "$( dirname -- "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )/src"

find "$SRC_DIR" -name ".git" -print0 | while IFS= read -r -d $'\0' GIT_DIR
do  
    CUR_DIR="${GIT_DIR%.git}"
    cd "$CUR_DIR" || exit 1
    echo -e "\e[32m#####--- Setting up $(basename "$CUR_DIR") \e[0m"

    if [[ "$CUR_DIR" == *"tod_"* || "$CUR_DIR" == *"tum_"* ]]; then
        CUR_REMOTE=$(git remote -v)
        URL=$(echo "$CUR_REMOTE" | awk '/fetch/ {gsub(/.*https:\/\/[^\/]+\//, "", $2); print $2}')
        git remote set-url --push origin "https://gitlab.lrz.de/$URL"
        echo -e "  --> Changed remote push origin to https://gitlab.lrz.de/$URL for $(basename "$CUR_DIR")\n"
    else 
        echo -e "  --> Kept default push origin for $(basename "$CUR_DIR")\n"
    fi
done

